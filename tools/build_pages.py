def lkr(n):
    return f"LKR {n:,}"


def picture(name, alt, eager=False):
    sets = lambda ext: ", ".join(f"/images/{name}-{w}.{ext} {w}w" for w in ((1280, 1920) if name == "hero" else (800, 1200, 1600)))
    fallback = "/images/hero-1920.jpg" if name == "hero" else f"/images/{name}-1200.jpg"
    load = 'fetchpriority="high"' if eager else 'loading="lazy"'
    return (f'<picture><source type="image/avif" srcset="{sets("avif")}" sizes="100vw">'
            f'<source type="image/webp" srcset="{sets("webp")}" sizes="100vw">'
            f'<img src="{fallback}" alt="{html.escape(alt)}" width="1600" height="1000" {load} decoding="async"></picture>')


